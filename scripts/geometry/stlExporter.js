/**
 * STL Exporter
 * Exports Three.js geometries to binary STL format.
 */

import {
    downloadBlob,
    geometryToBinarySTLBuffer,
    validateGeometryForSTL
} from './stlCore.js';
import { generateItemExportMesh } from './meshGenerator.js';
import { createZip } from '../storage/zipWriter.js';

/**
 * Export geometry to binary STL format
 */
export function exportToBinarySTL(geometry, filename = 'model', { upAxis = 'y' } = {}) {
    return geometryToBinarySTLBuffer(geometry, {
        header: `Binary STL - ${filename} - Generated by Dinnerware Generator`,
        logLabel: `dinnerware:${filename}`,
        validationMode: 'strict',
        validationOptions: { enforceOrientationConsistency: true },
        trackOrientationConflicts: true,
        upAxis
    });
}

/**
 * Download STL file
 */
export async function downloadSTL(bufferOrBlob, filename) {
    const blob = bufferOrBlob instanceof Blob
        ? bufferOrBlob
        : new Blob([bufferOrBlob], { type: 'application/octet-stream' });

    return downloadBlob(blob, filename);
}

/**
 * Build one item's export mesh and serialize it to a validated binary STL.
 * Uses the current dinnerware state (stateManager singleton).
 */
export function buildItemSTL(itemType, filename, { upAxis = 'y' } = {}) {
    const geometry = generateItemExportMesh(itemType);
    try {
        return exportToBinarySTL(geometry, filename, { upAxis });
    } finally {
        geometry.dispose();
    }
}

/**
 * Triangle count and binary STL size of an item's export mesh.
 */
export function measureItemSTL(itemType) {
    const geometry = generateItemExportMesh(itemType);
    try {
        const triangles = Math.floor((geometry.getIndex()?.count ?? geometry.getAttribute('position').count) / 3);
        return { triangles, bytes: 84 + triangles * 50 };
    } finally {
        geometry.dispose();
    }
}

const yieldToBrowser = () => new Promise(resolve => setTimeout(resolve, 0));

/**
 * STL builder backed by a module worker, falling back to the main thread
 * (yielding between items) where workers are unavailable.
 * @param {Object} state - Dinnerware state to export
 */
export function createSTLBuilder(state, { useWorker = typeof Worker !== 'undefined' } = {}) {
    let worker = null;
    let nextId = 0;
    const pending = new Map();
    if (useWorker) {
        try {
            worker = new Worker(new URL('./stlExportWorker.js', import.meta.url), { type: 'module' });
            worker.onmessage = ({ data }) => {
                const request = pending.get(data.id);
                if (!request) return;
                pending.delete(data.id);
                if (data.error) request.reject(new Error(data.error));
                else request.resolve(data.result);
            };
            worker.onerror = (event) => {
                event.preventDefault?.();
                const error = new Error(event.message || 'STL export worker failed');
                pending.forEach(request => request.reject(error));
                pending.clear();
                worker?.terminate();
                worker = null;
            };
        } catch (error) {
            console.warn('STL export worker unavailable, exporting on the main thread:', error);
            worker = null;
        }
    }
    const snapshot = JSON.parse(JSON.stringify(state));
    const request = (message) => new Promise((resolve, reject) => {
        const id = nextId++;
        pending.set(id, { resolve, reject });
        worker.postMessage({ id, state: snapshot, ...message });
    });

    return {
        usesWorker: () => worker !== null,
        async build(itemType, filename, { upAxis = 'y' } = {}) {
            if (worker) return request({ type: 'build', itemType, filename, upAxis });
            await yieldToBrowser();
            return buildItemSTL(itemType, filename, { upAxis });
        },
        async measure(itemType) {
            if (worker) return request({ type: 'measure', itemType });
            await yieldToBrowser();
            return measureItemSTL(itemType);
        },
        dispose() {
            worker?.terminate();
            worker = null;
            pending.clear();
        }
    };
}

/**
 * Export multiple items with progress callback. Each item is built,
 * validated and downloaded in turn, reporting progress before each.
 * @param {Array<{type: string, displayName: string}>} items
 * @param {string} projectName
 * @param {Function} progressCallback
 * @param {Object} options
 * @param {{build: Function}} options.builder - From createSTLBuilder
 * @param {'y'|'z'} [options.upAxis]
 * @param {boolean} [options.zip] - Download one ZIP instead of separate files
 */
export async function exportMultipleSTL(items, projectName, progressCallback, { builder, upAxis = 'y', zip = false } = {}) {
    const total = items.length;
    const archive = [];

    for (let i = 0; i < items.length; i++) {
        const { type, displayName } = items[i];
        const filename = `${projectName}_${type}.stl`;

        progressCallback?.({
            current: i + 1,
            total,
            itemName: displayName,
            progress: i / total
        });

        let buffer;
        try {
            buffer = await builder.build(type, filename, { upAxis });
        } catch (error) {
            throw new Error(`${displayName} failed STL validation: ${error.message}`);
        }
        if (zip) {
            archive.push({ name: filename, data: new Uint8Array(buffer) });
            continue;
        }
        await downloadSTL(buffer, filename);

        // Small delay between downloads to prevent browser blocking.
        if (i < items.length - 1) {
            await new Promise(resolve => setTimeout(resolve, 300));
        }
    }

    if (zip && archive.length) {
        progressCallback?.({ current: total, total, itemName: 'ZIP archive', progress: 0.99 });
        const bytes = await createZip(archive);
        await downloadBlob(new Blob([bytes], { type: 'application/zip' }), `${projectName}_stl.zip`);
    }

    progressCallback?.({
        current: total,
        total,
        itemName: 'Complete',
        progress: 1,
        complete: true
    });
}

/**
 * Validate geometry for STL export
 */
export function validateGeometry(geometry) {
    const validation = validateGeometryForSTL(geometry);

    return {
        valid: validation.valid,
        warnings: [...validation.warnings],
        triangleCount: validation.triangleCount,
        vertexCount: validation.vertexCount
    };
}
